void addError(RobotModelSpecProjectionResult& result, const std::string& code,
              const std::string& fieldPath, const std::string& message)
{
    StructureOptimizationDiagnostic diagnostic;
    diagnostic.code = code;
    diagnostic.severity = "Error";
    diagnostic.subsystem = "structure-optimizer";
    diagnostic.stage = "robot-model-spec-projection";
    diagnostic.fieldPath = fieldPath;
    diagnostic.message = message;
    result.diagnostics.push_back(diagnostic);
}

bool sameTransform(const rw::math::Transform3D<>& first,
                   const rw::math::Transform3D<>& second)
{
    if ((first.P() - second.P()).norm2() > 1e-24)
        return false;
    for (std::size_t row = 0; row < 3; ++row)
        for (std::size_t column = 0; column < 3; ++column)
            if (std::fabs(first.R()(row, column) - second.R()(row, column)) > 1e-12)
                return false;
    return true;
}

void assignPose(const rw::math::Transform3D<>& transform,
                std::array< double, 3 >& position,
                std::array< double, 3 >& rpyDeg)
{
    const rw::math::RPY<> rpy(transform.R());
    position = {{transform.P()(0), transform.P()(1), transform.P()(2)}};
    static const double radToDeg = 180.0 / rw::math::Pi;
    rpyDeg = {{rpy(0) * radToDeg, rpy(1) * radToDeg, rpy(2) * radToDeg}};
}

bool isZAxis(const rw::math::Vector3D<>& axis)
{
    return std::fabs(axis(0)) < 1e-12 && std::fabs(axis(1)) < 1e-12 &&
           std::fabs(axis(2) - 1.0) < 1e-12;
}

std::string jointType(CanonicalJointType type)
{
    switch (type) {
    case CanonicalJointType::Revolute: return "Revolute";
    case CanonicalJointType::Prismatic: return "Prismatic";
    case CanonicalJointType::Fixed: return "FixedFrame";
    }
    return "Unknown";
}

std::string geometryShape(CanonicalGeometryKind kind)
{
    switch (kind) {
    case CanonicalGeometryKind::Cylinder: return "Cylinder";
    case CanonicalGeometryKind::Box: return "Box";
    case CanonicalGeometryKind::Tube: return "Cylinder";
    case CanonicalGeometryKind::Mesh: return "Mesh";
    case CanonicalGeometryKind::Unknown: default: return "Unknown";
    }
}

bool chainContainsFrame(const CanonicalKinematicModel& model, const DeviceChain& chain,
                        const std::string& frameId)
{
    if (chain.rootFrameId == frameId)
        return true;
    for (const std::string& jointId : chain.orderedJointIds) {
        for (const JointEdge& joint : model.joints) {
            if (joint.id == jointId && joint.childFrameId == frameId)
                return true;
        }
    }
    return false;
}

template< class Binding >
void assignGeometry(const Binding& binding, DrawableSpec& drawable)
{
    drawable.name = binding.id;
    drawable.refFrame = binding.referenceFrameId;
    drawable.shape = geometryShape(binding.kind);
    drawable.filePath = binding.sourceObjectId;
    drawable.dimensions = {{binding.width, binding.height, binding.depth}};
    drawable.radius = binding.radius;
    drawable.length = binding.length;
    assignPose(binding.referenceToGeometry, drawable.pos, drawable.rpyDeg);
    drawable.autoGenerated = false;
}

template< class Binding >
void assignCollision(const Binding& binding, CollisionModelSpec& collision)
{
    collision.name = binding.id;
    collision.refFrame = binding.referenceFrameId;
    collision.shape = geometryShape(binding.kind);
    collision.filePath = binding.sourceObjectId;
    collision.dimensions = {{binding.width, binding.height, binding.depth}};
    collision.radius = binding.radius;
    collision.length = binding.length;
    assignPose(binding.referenceToGeometry, collision.pos, collision.rpyDeg);
    collision.enabled = true;
}

