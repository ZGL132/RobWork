import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import cp from 'node:child_process';
const out=path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1'));
const root=path.join(out,'repo'), read=p=>fs.readFileSync(p,'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
const json=f=>JSON.parse(read(path.join(out,f)));
const rawHash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const normHash=s=>crypto.createHash('sha256').update(s.replace(/\n*$/,'\n')).digest('hex');
const check=(ok,m)=>{if(!ok)throw new Error(m)};
const jsonFiles=fs.readdirSync(out).filter(f=>f.endsWith('.json'));
jsonFiles.forEach(json);
const r=json('review.json'),m=json('metadata-audit.json'),t=json('test-evidence-check.json');
check(r.result==='PASS'&&!r.fullT01Pass&&!r.T02Admission,'acceptance boundary');
check(r.definitionsReviewed===39&&m.definitions.length===39&&r.allDefinitionsRemainPending,'39 definitions');
check(new Set(m.definitions.map(d=>d.evidence)).size===39,'39 unique excerpt paths');
check(r.knownOpenProductFindings[0].id==='F-960'&&r.knownOpenProductFindings[0].status==='open','open finding');
check(t.totals.total===3&&t.totals.passed===2&&t.totals.failed===1&&t.totals.skipped===0&&t.totals.notRun===0,'probe counts');
for(const run of t.runs)for(const a of run.artifacts)check(rawHash(path.join(out,a.path))===a.rawSha256,'run artifact '+a.path);
for(const d of m.definitions){const lines=read(path.join(root,d.source.path)).split('\n'),region=lines.slice(d.source.startLine-1,d.source.endLine);check(normHash(region.join('\n'))===d.source.sha256,d.functionId+' region');const excerpt=d.source.path+'\n'+d.source.qualifiedSymbol+'\n'+region.map((l,i)=>`${d.source.startLine+i}: ${l}`).join('\n')+'\n';check(read(path.join(out,d.evidence))===excerpt,d.functionId+' excerpt');check(d.status==='pending'&&d.decision==='pending',d.functionId+' status');}
for(const key of ['clone','checkout','configure','build','metadata-audit','write-review','task','reuse','docs'])check(read(path.join(out,key+'.exit.txt')).trim()==='0',key+' exit');
check(read(path.join(out,'task.log')).includes('validate-task: PASS'),'task marker');
check(read(path.join(out,'reuse.log')).includes('validate-reuse: PASS governance only'),'reuse marker');
check(read(path.join(out,'docs.log')).includes('validate-docs: PASS'),'docs marker');
for(const b of json('build-wiring.json'))check(rawHash(path.join(out,b.copy))===b.rawSha256,'generated copy '+b.copy);
const core=read(path.join(out,'generated-ird-core_sdurws_ird_core.vcxproj'));
const kit=read(path.join(out,'generated-ird-testkit_sdurws_ird_testkit.vcxproj'));
const probe=read(path.join(out,'generated-ird_reuse_audit_probe.vcxproj'));
check(core.includes('core\\src\\Compare.cpp'),'original core TU wiring');
check(kit.includes('testkit\\src\\Dataset.cpp'),'original testkit TU wiring');
check(probe.includes('MatchingSuitabilityTest.cpp')&&probe.includes('TestMainReport.cpp')&&probe.includes('sdurws_ird_testkit.vcxproj'),'probe wiring');
const sha=cp.execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
const status=cp.execFileSync('git',['status','--porcelain'],{cwd:root,encoding:'utf8'});
check(sha===r.reviewedCommit&&status==='','frozen clone');
fs.writeFileSync(path.join(out,'git-status-end.txt'),status);
const result={result:'PASS',reviewedCommit:sha,repositoryClean:true,jsonFilesParsed:jsonFiles.length,definitionsVerified:39,gateCounts:{passed:3,failed:0,skipped:0},tests:t.totals,F960:'OPEN',fullT01Pass:false,T02Admission:false};
fs.writeFileSync(path.join(out,'review-consistency-check.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
